from fastapi import APIRouter
from app.core.database import supabase
from app.utils.token_counter import count_tokens
import json

router = APIRouter(prefix="/projects/{project_id}/context", tags=["Context"])

def get_memory(project_id: str):
    res = supabase.table("project_memory")\
        .select("*")\
        .eq("project_id", project_id)\
        .execute()
    return res.data[0] if res.data else {"memory_data": {}, "version": 1}

def to_markdown(memory_data: dict, project_name: str, version: int) -> str:
    lines = [
        f"# {project_name} — Project Memory",
        f"_ContextBridge Export • Memory Version {version}_\n",
        "> This file was generated by ContextBridge.",
        "> Paste it at the start of your AI coding agent session to restore project context.\n",
        "---\n"
    ]
    sections = [
        ("project_overview", "## Project Overview", "text"),
        ("requirements", "## Requirements", "list"),
        ("architecture", "## Architecture", "text"),
        ("technologies", "## Technologies", "list"),
        ("current_progress", "## Current Progress", "list"),
        ("key_decisions", "## Key Decisions", "list"),
        ("pending_tasks", "## Pending Tasks", "list"),
        ("known_issues", "## Known Issues", "list"),
        ("agent_instructions", "## Agent Instructions", "list"),
    ]
    for key, header, kind in sections:
        value = memory_data.get(key)
        if not value:
            continue
        lines.append(header)
        if kind == "list":
            for item in value:
                lines.append(f"- {item}")
        else:
            lines.append(str(value))
        lines.append("")
    return "\n".join(lines)

@router.get("/export/markdown")
def export_markdown(project_id: str):
    proj = supabase.table("projects").select("*").eq("id", project_id).execute()
    name = proj.data[0]["name"] if proj.data else "Project"
    record = get_memory(project_id)
    original = json.dumps(record["memory_data"], indent=2)
    md = to_markdown(record["memory_data"], name, record["version"])
    return {
        "markdown": md,
        "original_tokens": count_tokens(original),
        "compressed_tokens": count_tokens(md),
    }

@router.get("/export/json")
def export_json(project_id: str):
    proj = supabase.table("projects").select("*").eq("id", project_id).execute()
    project = proj.data[0] if proj.data else {}
    record = get_memory(project_id)
    return {
        "memory_data": record["memory_data"],
        "version": record["version"],
        "project_name": project.get("name", ""),
        "exported_at": __import__("datetime").datetime.utcnow().isoformat()
    }


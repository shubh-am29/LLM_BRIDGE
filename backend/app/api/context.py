@router.get("/export/package")
def export_package(project_id: str):
    proj = supabase.table("projects").select("*").eq("id", project_id).execute()
    project = proj.data[0] if proj.data else {}
    record = get_memory(project_id)
    name = project.get("name", "Project")
    version = record["version"]

    md = to_markdown(record["memory_data"], name, version)
    config = {
        "project_id": project_id,
        "project_name": name,
        "memory_format": "contextbridge-v1",
        "export_version": version
    }
    return {
        "project_memory_md": md,
        "project_memory_json": record["memory_data"],
        "project_config_json": config,
        "agent_instructions_md": AGENT_INSTRUCTIONS_MD
    }